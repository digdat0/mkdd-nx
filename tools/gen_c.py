def parse_vn(tok):
    if tok == "_":
        return None
    k, off, size = VN.fullmatch(tok).groups()
    return k, int(off, 16), int(size)


def parse_op(text):
    head, rest = text.split(" = ", 1) if " = " in text else (text, "")
    parts = head.split(" ")
    mnem = parts[0]
    name = None
    if mnem.startswith("CALLOTHER["):
        name = mnem[10:-1]
        mnem = "CALLOTHER"
    out = parse_vn(parts[1]) if len(parts) > 1 else None
    ins = [parse_vn(t) for t in rest.split()] if rest else []
    return mnem, name, out, ins


def write_if_changed(path, data):
    """Only touch files whose content changed, so make/ninja rebuild just what changed."""
    if isinstance(data, str):
        data = data.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return
    path.write_bytes(data)


def mask(v, s):
    return v & ((1 << (8 * s)) - 1)


def ends_block(pcode):
    """True if control never falls through past this instruction unconditionally."""
    for text in pcode.split(" | "):
        if text.split(" ", 1)[0] in ("BRANCH", "BRANCHIND", "RETURN"):
            return True
    return False


def find_leaders(instructions, entries):
    code = {int(r["addr"], 16) for r in instructions}
    leaders = set(entries)
    for r in instructions:
        for text in r["pcode"].split(" | "):
            if not text.startswith(("BRANCH ", "CBRANCH ", "CALL ")):
                continue
            ins = parse_op(text)[3]
            if ins and ins[0] and ins[0][0] == "M":
                leaders.add(ins[0][1])
    # Jumps through a register built just before: lis rA,hi / addi (subi) rA,rA,lo / mtspr CTR,rA /
    # bctr (MKDD Plus jumps into and back out of a code cave this way).
    built = 0
    li = re.compile(r"lis (r\d+),(-?0x[0-9a-f]+|-?\d+)$")
    ai = re.compile(r"(addi|subi) (r\d+),(r\d+),(-?0x[0-9a-f]+|-?\d+)$")
    for i in range(len(instructions) - 3):
        m1 = li.match(instructions[i]["asm"])
        if not m1:
            continue
        m2 = ai.match(instructions[i + 1]["asm"])
        if not (m2 and m2[2] == m1[1] and m2[3] == m1[1] and instructions[i + 2]["asm"] == f"mtspr CTR,{m1[1]}"
                and instructions[i + 3]["asm"] == "bctr"):
            continue
        lo = int(m2[4], 0) * (-1 if m2[1] == "subi" else 1)
        t = ((int(m1[2], 0) << 16) + lo) & 0xFFFFFFFF
        if t in code and t not in leaders:
            leaders.add(t)
            built += 1
    data_refs = 0
    for r in read("memory.csv"):
        if "text" in r["section"]:
            continue
        raw = bytes.fromhex(r["hex"])
        for i in range(0, len(raw) - 3, 4):
            w = int.from_bytes(raw[i:i + 4], "big")
            if w in code and w not in leaders:
                leaders.add(w)
                data_refs += 1
    print(f"block leaders: {len(leaders)} ({data_refs} from data references, {built} built in registers)", flush=True)
    return leaders


