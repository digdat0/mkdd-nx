/* The XF stage (transform, lighting, texgen) as the TEV programs' vertex shader. Line for line the
 * same as gx_xf_eval in runtime/gx.c, which MKDD_XFCHECK compares with the decoder's CPU path on
 * PC; keep both in step. Record layout: build_record in runtime/gx.c. Vertices with
 * a_ids.x == 0xFFFFFFFF were transformed on the CPU and pass through. */
#pragma once

static const char *XF_VS =
    "#version 320 es\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "precision highp usamplerBuffer;\n"
    "layout(location=0) in vec4 a_pos;\n"
    "layout(location=1) in vec4 a_c0;\n"
    "layout(location=2) in vec4 a_c1;\n"
    "layout(location=3) in vec4 a_uv01;\n"
    "layout(location=4) in vec4 a_uv23;\n"
    "layout(location=5) in vec4 a_uv45;\n"
    "layout(location=6) in vec4 a_uv67;\n"
    "layout(location=7) in vec3 a_nrm;\n"
    "layout(location=8) in uvec2 a_ids;\n"
    "layout(binding=8) uniform usamplerBuffer u_xf;\n"
    "uniform float u_squeeze; // widescreen 4:3 HUD: x of flagged 2D vertices * (1 - u_squeeze)\n"
    "layout(location=0) out vec4 v_c0; layout(location=1) out vec4 v_c1; layout(location=2) out vec4 v_uv01;"
    "layout(location=3) out vec4 v_uv23; layout(location=4) out vec4 v_uv45; layout(location=5) out vec4 v_uv67;\n"
    "uvec4 T(uint i) { return texelFetch(u_xf, int(i)); }\n"
    "vec4 F(uint i) { return uintBitsToFloat(texelFetch(u_xf, int(i))); }\n"
    "vec4 rgba8(uint v) { return vec4(float(v >> 24), float((v >> 16) & 255u), float((v >> 8) & 255u), float(v & 255u)) / 255.0; }\n"
    "vec3 nrm3(vec3 v) { float l2 = dot(v, v); return l2 > 0.0 ? v * (1.0 / sqrt(l2)) : v; }\n"
    "vec4 q8(vec4 x) { return floor(x * 255.0 + 0.5) / 255.0; }\n"
    "vec4 lit_part(uvec4 p, uint lb, vec3 pos, vec3 n, vec4 vcol, bool hv) {\n"
    "    uint ctrl = p.x;\n"
    "    vec4 acc = (((ctrl >> 6) & 1u) != 0u && hv) ? vcol : rgba8(p.z);\n"
    "    uint mask = ((ctrl >> 2) & 15u) | (((ctrl >> 11) & 15u) << 4);\n"
    "    uint dfn = (ctrl >> 7) & 3u, afn = (ctrl >> 9) & 3u;\n"
    "    for (uint l = 0u; l < 8u; l++) {\n"
    "        if ((mask & (1u << l)) == 0u) continue;\n"
    "        uint b = lb + 5u * l;\n"
    "        vec4 col = rgba8(T(b).x);\n"
    "        vec3 cs = F(b + 1u).xyz, ds = F(b + 2u).xyz, lp = F(b + 3u).xyz, ld = F(b + 4u).xyz;\n"
    "        vec3 tl = lp - pos, dir;\n"
    "        float attn;\n"
    "        if (afn == 1u) {\n"
    "            vec3 k = ds;\n"
    "            if (dfn != 0u) { float l2 = dot(ds, ds); k = ds * (l2 > 0.0 ? 1.0 / sqrt(l2) : 1.0); }\n"
    "            dir = nrm3(tl);\n"
    "            float a = dot(n, dir) >= 0.0 ? max(dot(n, ld), 0.0) : 0.0;\n"
    "            float num = max(cs.x + cs.y * a + cs.z * a * a, 0.0);\n"
    "            float den = k.x + k.y * a + k.z * a * a;\n"
    "            attn = den != 0.0 ? num / den : 0.0;\n"
    "        } else if (afn == 3u) {\n"
    "            float d2 = dot(tl, tl), d = sqrt(d2);\n"
    "            dir = d > 0.0 ? tl * (1.0 / d) : tl;\n"
    "            float cc = max(dot(dir, ld), 0.0);\n"
    "            float num = max(cs.x + cs.y * cc + cs.z * cc * cc, 0.0);\n"
    "            float den = ds.x + ds.y * d + ds.z * d2;\n"
    "            attn = den != 0.0 ? num / den : 0.0;\n"
    "        } else {\n"
    "            dir = nrm3(tl);\n"
    "            if (dot(dir, dir) == 0.0) dir = n;\n"
    "            attn = 1.0;\n"
    "        }\n"
    "        float ndl = dot(dir, n);\n"
    "        float diff = dfn == 0u ? 1.0 : dfn == 1u ? ndl : max(ndl, 0.0);\n"
    "        vec4 x = (attn * diff * 255.0) * col;\n"
    "        acc += sign(x) * floor(abs(x) + 0.5) / 255.0;\n"
    "    }\n"
    "    return clamp(acc, 0.0, 1.0);\n"
    "}\n"
    "vec4 channel(uint rec, uint ch, uint chans, uint lb, vec3 view, vec3 vn, vec4 vcol, bool hv) {\n"
    "    if (ch >= max(chans, 1u)) return vec4(0.0);\n"
    "    uvec4 pc = T(rec + 4u + 2u * ch), pa = T(rec + 5u + 2u * ch);\n"
    "    vec4 mc = ((pc.x & 1u) != 0u && hv) ? vcol : rgba8(pc.y);\n"
    "    vec4 ma = ((pa.x & 1u) != 0u && hv) ? vcol : rgba8(pa.y);\n"
    "    vec4 o;\n"
    "    o.rgb = ((pc.x >> 1) & 1u) != 0u ? lit_part(pc, lb, view, vn, vcol, hv).rgb * mc.rgb : mc.rgb;\n"
    "    o.a = ((pa.x >> 1) & 1u) != 0u ? lit_part(pa, lb, view, vn, vcol, hv).a * ma.a : ma.a;\n"
    "    return o;\n"
    "}\n"
    "vec2 texgen(uint t, uint tm, vec3 pos, vec3 nrm, vec2 src) {\n"
    "    uvec4 info = T(t);\n"
    "    uint row = (info.x >> 7) & 31u, ty = (info.x >> 4) & 7u;\n"
    "    bool stq = ((info.x >> 1) & 1u) != 0u;\n"
    "    vec4 i4 = row == 0u ? vec4(pos, 1.0) : row == 1u ? vec4(nrm, 1.0) : (row >= 5u && row <= 12u) ? vec4(src, 1.0, 1.0) : vec4(0.0, 0.0, 1.0, 1.0);\n"
    "    if (ty != 0u) return i4.xy;\n"
    "    uint mb = tm != 0u ? tm : t + 1u;\n"
    "    vec3 v = vec3(dot(F(mb), i4), dot(F(mb + 1u), i4), stq ? dot(F(mb + 2u), i4) : 1.0);\n"
    "    if (info.z != 0u) {\n"
    "        if (((info.y >> 8) & 1u) != 0u) { float len = length(v); if (len > 1e-12) v /= len; }\n"
    "        vec4 p0 = F(t + 4u), p1 = F(t + 5u), p2 = F(t + 6u);\n"
    "        v = vec3(dot(p0.xyz, v) + p0.w, dot(p1.xyz, v) + p1.w, dot(p2.xyz, v) + p2.w);\n"
    "    }\n"
    "    if (stq && abs(v.z) > 1e-6) return v.xy / v.z;\n"
    "    return v.xy;\n"
    "}\n"
    "void main() {\n"
    "    vec4 cp;\n"
    "    if (a_ids.x == 0xFFFFFFFFu) {\n"
    "        cp = a_pos;\n"
    "        v_c0 = a_c0; v_c1 = a_c1; v_uv01 = a_uv01; v_uv23 = a_uv23; v_uv45 = a_uv45; v_uv67 = a_uv67;\n"
    "    } else {\n"
    "        uint rec = a_ids.x & 0x0FFFFFFFu, m = a_ids.y;\n"
    "        uint tms[8] = uint[8](0u, 0u, 0u, 0u, 0u, 0u, 0u, 0u);\n"
    "        if ((m & 0x80000000u) != 0u) {\n"
    "            uint ib = m & 0x7FFFFFFFu;\n"
    "            uvec4 i0 = T(ib), i1 = T(ib + 1u), i2 = T(ib + 2u);\n"
    "            m = i0.x;\n"
    "            tms = uint[8](i0.y, i0.z, i0.w, i1.x, i1.y, i1.z, i1.w, i2.x);\n"
    "        }\n"
    "        vec4 p4 = vec4(a_pos.xyz, 1.0);\n"
    "        vec3 view = vec3(dot(F(m), p4), dot(F(m + 1u), p4), dot(F(m + 2u), p4));\n"
    "        vec3 n0 = a_nrm * (1.0 / 16384.0); // compact vertices: int16 x 16384\n"
    "        vec3 vn = vec3(dot(F(m + 3u).xyz, n0), dot(F(m + 4u).xyz, n0), dot(F(m + 5u).xyz, n0));\n"
    "        float l2 = dot(vn, vn);\n"
    "        if (l2 > 1e-12) vn *= 1.0 / sqrt(l2);\n"
    "        vec4 r0 = F(rec), r1 = F(rec + 1u), r2 = F(rec + 2u);\n"
    "        uvec4 r3 = T(rec + 3u);\n"
    "        uint flags = r3.x, zop = (flags >> 1) & 3u, chans = (flags >> 3) & 3u;\n"
    "        vec4 p;\n"
    "        if ((flags & 1u) == 0u) p = vec4(r0.x * view.x + r0.y * view.z, r0.z * view.y + r0.w * view.z, r1.x * view.z + r1.y, -view.z);\n"
    "        else p = vec4(r0.x * view.x + r0.y, r0.z * view.y + r0.w, r1.x * view.z + r1.y, 1.0);\n"
    "        float w = p.w, zval = uintBitsToFloat(r3.y);\n"
    "        float zc = zop == 2u ? zval * w : zop != 0u ? r1.w * w + r1.z * p.z + zval * w : r1.w * w + r1.z * p.z;\n"
    "        cp = vec4(r2.x * p.x + r2.y * w, r2.z * p.y + r2.w * w, zc * (1.0 / 16777215.0), w);\n"
    "        if ((a_ids.x & 0x40000000u) != 0u) {\n"
    "            float side = (a_ids.x & 0x20000000u) != 0u ? -1.0 : (a_ids.x & 0x10000000u) != 0u ? 1.0 : 0.0;\n"
    "            cp.x = cp.x * (1.0 - u_squeeze) + side * u_squeeze * cp.w;\n"
    "        }\n"
    "        v_c0 = q8(channel(rec, 0u, chans, r3.z, view, vn, a_c0, ((flags >> 5) & 1u) != 0u));\n"
    "        v_c1 = q8(channel(rec, 1u, chans, r3.z, view, vn, a_c1, ((flags >> 6) & 1u) != 0u));\n"
    "        vec2 src[8] = vec2[8](a_uv01.xy, a_uv01.zw, a_uv23.xy, a_uv23.zw, a_uv45.xy, a_uv45.zw, a_uv67.xy, a_uv67.zw);\n"
    "        vec2 uv[8];\n"
    "        for (uint i = 0u; i < 8u; i++)\n"
    "            uv[i] = (r3.w & (1u << i)) != 0u ? texgen(rec + 8u + 7u * i, tms[i], a_pos.xyz, n0, src[i]) : vec2(0.0);\n"
    "        v_uv01 = vec4(uv[0], uv[1]); v_uv23 = vec4(uv[2], uv[3]); v_uv45 = vec4(uv[4], uv[5]); v_uv67 = vec4(uv[6], uv[7]);\n"
    "    }\n"
    "    // y flipped (texel row 0 = top); depth 0..1 (wgpu) -> -1..1 (GL), same stored depth.\n"
    "    gl_Position = vec4(cp.x, -cp.y, 2.0 * cp.z - cp.w, cp.w);\n"
    "}\n";
